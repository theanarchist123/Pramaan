// Builds docs/review/hindi-copy-review.md: every Hindi string next to its English original, for a native speaker to check and tick off.
// Run: node scripts/hindi-review-sheet.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const src = readFileSync(new URL("../src/lib/i18n.tsx", import.meta.url), "utf8");
const block = (name, open) => {
  const start = src.indexOf(open);
  const end = src.indexOf("\n}", start + 5);
  const body = src.slice(start, end);
  const out = {};
  for (const m of body.matchAll(/"([a-zA-Z0-9_.]+)":\s*"((?:[^"\\]|\\.)*)"/g)) out[m[1]] = m[2].replace(/\\"/g, '"');
  return out;
};
const en = block("en", "const en = {");
const hi = block("hi", "const hi: Partial<Record<Key, string>> = {");
const rows = Object.keys(hi).map((k) => `| \`${k}\` | ${(en[k] ?? "(no English original)").replace(/\|/g, "\\|")} | ${hi[k].replace(/\|/g, "\\|")} | [ ] |`);
const missing = Object.keys(en).filter((k) => !(k in hi));
const md = `# Hindi copy review sheet

For a native Hindi speaker. Tick the last column when the Hindi reads naturally (not like a translation), is respectful in tone for senior people, and means the same as the English.
Generated by \`apps/web/scripts/hindi-review-sheet.mjs\` from \`src/lib/i18n.tsx\`. ${rows.length} Hindi strings; ${missing.length} English strings have no Hindi yet (they show in English).

| Key | English | Hindi | Reviewed |
|---|---|---|---|
${rows.join("\n")}

## Strings with no Hindi yet
${missing.map((k) => `- \`${k}\`: ${en[k]}`).join("\n")}

## Also in the app, outside this file
- The reply Saathi adds when a name could not be recorded (backend/app/api/onboarding.py, the Hindi sentence in \`ask\`).
`;
mkdirSync(new URL("../../../docs/review/", import.meta.url), { recursive: true });
writeFileSync(new URL("../../../docs/review/hindi-copy-review.md", import.meta.url), md, "utf8");
console.log(`wrote docs/review/hindi-copy-review.md (${rows.length} Hindi, ${missing.length} without Hindi)`);
